// Campaña del Modo Aventura: definición declarativa de niveles.
//
// Veinte capítulos de diez niveles, uno por tierra del mapa, cada uno con su jefe al final.
// Los poderes no se declaran acá: los estrena el calendario de `adventure.js` (primero los
// doce neutrales, después los treinta de clase, hasta el nivel 175) y cada nivel pelea
// con su combinación fija (`levelPowers`). Lo que crece nivel a nivel, además, es el
// rival: cartas de mochila y, más adelante, partes evolucionadas (ver `RIVAL_LADDER`).
//
// Para agregar un nivel nuevo a la campaña:
// 1. Agregá un nuevo objeto al final del array ADVENTURE_CAMPAIGN.
// 2. Definí solo los campos propios del nivel:
//    - `name` (string): el título, sin "Nivel N" ni "Jefe": eso lo pone el juego (ver
//      `levelKicker` en `adventure.js`), así el número nunca queda viejo.
//    - `description` (string): Texto descriptivo del combate y los poderes en juego.
//    - `rival` (string): ID del rival en `RIVALS` de `src/axies.js`.
//    - `difficulty` (string): 'facil' | 'normal' | 'duro'.
//    - `newPowers` (string[], opcional): lo que estrena el nivel, si no es lo del calendario
//      (`UNLOCK_ORDER` y `UNLOCK_LEVELS` en `src/adventure.js`). La campaña no lo usa.
//    - `stage` (string): dónde se pelea, un id de `STAGES` en `src/stages.js` (plaza, coliseo, pirata, playa, nevada, otono, guarida).
//    - `hp` (number, opcional): la vida del rival, si no es la de siempre (los jefes).
//    - `charmPowers` (string[], opcional): los poderes de las partes con amuleto de un
//      jefe, repartidos en orden. Si no dice, los de la combinación del nivel.
//    - `extras` (opcional): las cartas de mochila del rival (`{ symbols, power }`), si
//      no son las de la escalera.
//    - `showcase` (string[], opcional): Poderes o cartas especiales extra para destacar en la ficha del lobby (ej: ['freegame']).
//    - `activePowers` (string[], opcional): reemplaza la combinación fija de poderes del
//      nivel (ver `levelPowers` en `src/adventure.js`).
//
// Lo demás se deriva en `src/adventure.js`: el `id` (1-based según la posición), los
// poderes desbloqueados hasta ahí (`unlocked`), lo que trae el rival según la escalera
// (`extras`, `evolved`) y su id completo (`rival`, con las evoluciones: `'lobo+2'`).

